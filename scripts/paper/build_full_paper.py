"""Build the full paper's LaTeX source and PDF from its Markdown source.

The Markdown file is the single source. This script writes `docs/paper/latex/main.tex`
(NeurIPS 2026 style, preprint option) and compiles it with xelatex into `outputs/paper/full/`.

Usage (from the repo root):
    python3 -I scripts/paper/build_full_paper.py [--src docs/paper/full/paper-full.md] [--no-pdf]

Conventions the Markdown must follow (the script asserts them):
- `# Title`, then a bold subtitle line, then an optional italic note line;
- `## Abstract`, numbered sections `## 1. ...` / `### 1.1 ...`, `## References` (numbered list),
  then appendices `## Appendix A. ...` / `### A.1 ...` in letter order;
- a figure is `![](path.png)`, a blank line, then `**Figure N.** caption` (N in order);
- a table is `**Table N.** caption`, a blank line, then a pipe table (N in order).
Needs pandoc (3.x) and xelatex; figures are taken as PDF next to the PNG named in the source.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LATEX_DIR = ROOT / "docs" / "paper" / "latex"
OUT_DIR = ROOT / "outputs" / "paper" / "full"
TEX_BIN = "/Library/TeX/texbin"

SUPERSCRIPT = str.maketrans("⁰¹²³⁴⁵⁶⁷⁸⁹⁻", "0123456789-")

PREAMBLE = r"""% GENERATED by scripts/paper/build_full_paper.py from <<src>> -- do not edit by hand.
% Paper 1, full version, in the official NeurIPS 2026 style (preprint option).
% Style: neurips_2026.sty from Formatting_Instructions_For_NeurIPS_2026.zip (zip sha256 82473931e3ef), unmodified.
% Build: python3 -I scripts/paper/build_full_paper.py (xelatex, STIX Two Text).
\documentclass{article}
\usepackage[preprint]{neurips_2026}
\usepackage{fontspec}
\setmainfont{STIX Two Text}
\setmonofont[Scale=0.85]{Menlo}
\usepackage{hyperref}
\hypersetup{colorlinks=true,linkcolor=blue!50!black,urlcolor=blue!50!black}
\usepackage{url}
\usepackage{booktabs,longtable,array,calc}
\usepackage{amsmath,amssymb}
\usepackage{microtype}
\usepackage{xcolor}
\usepackage{graphicx}
\usepackage{float}
\usepackage{etoolbox}
\AtBeginEnvironment{longtable}{\small}
\setlength{\LTpre}{6pt}\setlength{\LTpost}{6pt}
\makeatletter\@ifundefined{c@none}{\newcounter{none}}{}\makeatother
\providecommand{\tightlist}{\setlength{\itemsep}{0pt}\setlength{\parskip}{0pt}}
\makeatletter
\newsavebox\pandoc@box
\newcommand*\pandocbounded[1]{%
  \sbox\pandoc@box{#1}%
  \Gscale@div\@tempa{\textheight}{\dimexpr\ht\pandoc@box+\dp\pandoc@box\relax}%
  \Gscale@div\@tempb{\linewidth}{\wd\pandoc@box}%
  \ifdim\@tempb\p@<\@tempa\p@\let\@tempa\@tempb\fi
  \ifdim\@tempa\p@<\p@\scalebox{\@tempa}{\usebox\pandoc@box}%
  \else\usebox{\pandoc@box}\fi}
\makeatother
\renewcommand{\arraystretch}{1.15}

\title{<<title>>}
\author{Ozgun Genc\\\texttt{ozgungenc@gmail.com}}

\begin{document}
\maketitle

\begin{center}
\begin{minipage}{0.9\linewidth}
\centering\itshape <<subtitle>>
\end{minipage}
\end{center}
<<note>>
\begin{abstract}
<<abstract>>
\end{abstract}

<<body>>

\section*{References}
\small
<<refs>>
\normalsize

\appendix
\AtBeginEnvironment{longtable}{\footnotesize}
\setlength{\tabcolsep}{4pt}
\setlength{\emergencystretch}{3em}
<<appendices>>

\end{document}
"""


def strip_comments(s: str) -> str:
    return re.sub(r"<!--.*?-->", "", s, flags=re.S)


def superscripts(s: str) -> str:
    # "10⁻⁷" -> "10^{-7}" inside math, keeping the rest of the text as is.
    def rep(m: re.Match) -> str:
        return f"$10^{{{m.group(1).translate(SUPERSCRIPT)}}}$"
    return re.sub(r"10([⁰¹²³⁴⁵⁶⁷⁸⁹⁻]+)", rep, s)


def convert_figures(s: str, expect: list[int]) -> str:
    pat = re.compile(r"!\[\]\(([^)]+)\)\s*\n\s*\n\*\*Figure (\d+)\.\*\* ([^\n]+)")

    def rep(m: re.Match) -> str:
        expect.append(int(m.group(2)))
        path = m.group(1).replace(".png", ".pdf")
        cap = m.group(3).strip()
        return f"![{cap}]({path}){{width=100%}}"
    return pat.sub(rep, s)


def convert_tables(s: str, expect: list[int]) -> str:
    lines = s.split("\n")
    out: list[str] = []
    i = 0
    while i < len(lines):
        m = re.match(r"\*\*Table (\d+)\.\*\* (.+)", lines[i])
        if m:
            expect.append(int(m.group(1)))
            cap = m.group(2).strip()
            i += 1
            while i < len(lines) and not lines[i].startswith("|"):
                i += 1
            while i < len(lines) and lines[i].startswith("|"):
                out.append(lines[i])
                i += 1
            out.append("")
            out.append(f"Table: {cap}")
            out.append("")
            continue
        out.append(lines[i])
        i += 1
    return "\n".join(out)


def strip_heading_numbers(s: str) -> str:
    s = re.sub(r"^(##+) Appendix [A-Z]\. ", r"\1 ", s, flags=re.M)
    s = re.sub(r"^(###+) [A-Z]\.\d+ ", r"\1 ", s, flags=re.M)
    s = re.sub(r"^(##+) \d+(\.\d+)*\.? ", r"\1 ", s, flags=re.M)
    return s


def pandoc(md: str, shift: int = -1) -> str:
    cmd = ["pandoc", "-f", "markdown+pipe_tables", "-t", "latex", "--wrap=preserve",
           f"--shift-heading-level-by={shift}"]
    r = subprocess.run(cmd, input=md, capture_output=True, text=True, check=True)
    tex = r.stdout
    tex = tex.replace("\\begin{figure}\n", "\\begin{figure}[htbp]\n")
    return tex


def split_source(s: str) -> dict[str, str]:
    m = re.match(r"\s*# (.+?)\n\s*\n\*\*(.+?)\*\*\n\s*\n(?:\*(.+?)\*\n)?", s)
    assert m, "title, bold subtitle and optional italic note expected at the top"
    title, subtitle, note = m.group(1), m.group(2), m.group(3) or ""
    rest = s[m.end():]
    a0 = rest.index("## Abstract")
    b0 = rest.index("\n## 1. ")
    r0 = rest.index("\n## References")
    app = re.search(r"\n## Appendix A\. ", rest)
    abstract = rest[a0 + len("## Abstract"):b0]
    body = rest[b0:r0]
    refs = rest[r0 + len("\n## References"):(app.start() if app else len(rest))]
    appendices = rest[app.start():] if app else ""
    return dict(title=title, subtitle=subtitle, note=note, abstract=abstract, body=body,
                refs=refs, appendices=appendices)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="docs/paper/full/paper-full.md")
    ap.add_argument("--no-pdf", action="store_true")
    args = ap.parse_args()
    src = ROOT / args.src
    s = superscripts(strip_comments(src.read_text()))
    for ch, math in (("↓", "\\downarrow"), ("→", "\\rightarrow"), ("≤", "\\le"), ("≥", "\\ge"), ("↑", "\\uparrow"), ("⌊", "\\lfloor"), ("⌋", "\\rfloor")):
        s = s.replace(ch, f"${math}$")
    figs: list[int] = []
    tabs: list[int] = []
    s = convert_figures(s, figs)
    s = convert_tables(s, tabs)
    assert figs == list(range(1, len(figs) + 1)), f"figures out of order: {figs}"
    assert tabs == list(range(1, len(tabs) + 1)), f"tables out of order: {tabs}"
    parts = split_source(s)
    letters = re.findall(r"^## Appendix ([A-Z])\. ", parts["appendices"], flags=re.M)
    assert letters == [chr(ord("A") + i) for i in range(len(letters))], f"appendix letters: {letters}"
    for k in ("body", "appendices"):
        parts[k] = strip_heading_numbers(parts[k])
    note = ""
    if parts["note"]:
        note = "\\begin{center}\\small " + pandoc(parts["note"]).strip() + "\\end{center}\n"
    fill = dict(
        src=args.src,
        title=parts["title"],
        subtitle=pandoc(parts["subtitle"]).strip(),
        note=note,
        abstract=pandoc(parts["abstract"]).strip(),
        body=pandoc(parts["body"]).strip(),
        refs=pandoc(parts["refs"]).strip(),
        appendices=pandoc(parts["appendices"]).strip(),
    )
    tex = PREAMBLE
    for k, v in fill.items():
        tex = tex.replace(f"<<{k}>>", v)
    out_tex = LATEX_DIR / "main.tex"
    out_tex.write_text(tex)
    print(f"wrote {out_tex.relative_to(ROOT)}: {len(figs)} figures, {len(tabs)} tables, "
          f"{len(letters)} appendices")
    if args.no_pdf:
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    env_path = f"{TEX_BIN}:/usr/bin:/bin"
    for _ in range(2):
        r = subprocess.run(["xelatex", "-interaction=nonstopmode", "-halt-on-error",
                            f"-output-directory={OUT_DIR}", "main.tex"],
                           cwd=LATEX_DIR, capture_output=True, text=True,
                           env={"PATH": env_path, "HOME": str(Path.home())})
        if r.returncode != 0:
            print(r.stdout[-3000:])
            return 1
    log = (OUT_DIR / "main.log").read_text(errors="replace")
    missing = sorted(set(re.findall(r"Missing character: There is no (.) ", log)))
    over = len(re.findall(r"Overfull \\hbox", log))
    pages = re.search(r"Output written on .*?\((\d+) pages", log, flags=re.S)
    print(f"pdf: {OUT_DIR / 'main.pdf'} ({pages.group(1) if pages else '?'} pages); "
          f"missing glyphs: {missing or 'none'}; overfull boxes: {over}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
