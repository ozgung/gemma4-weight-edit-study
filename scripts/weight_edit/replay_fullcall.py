"""Full-call replay: regenerate BOTH new_string and old_string of an edit_file call under one arm (MLX, bf16).  Owner: Claude.

    outputs/small_model/mlx_venv/bin/python -I scripts/weight_edit/replay_fullcall.py \\
        --calls outputs/weight_edit/claude/replay_ood/calls.jsonl --keys outputs/weight_edit/claude/replay_ood/usable_keys.txt \\
        --draws 2 [--edit DIR] --out outputs/weight_edit/claude/gate_r2/fullcall/gen_<arm>.jsonl
    (then score with the harness venv: scripts/weight_edit/replay_score_fullcall.py)

Why (amendment 2026-11-05, before any round-2 candidate was generated on the gate set): in 727/730 search calls and
320/320 gate calls the model writes new_string BEFORE old_string, so the frozen-prefix replay (replay_gen.py) keeps the
served model's new_string and regenerates only old_string. When an edit makes old_string an exact copy, the harness no
longer takes its unescape fallback and inserts the frozen, still-escaped new_string verbatim; the file stops compiling.
The registered compile guard therefore pairs an edited old_string with an unedited new_string. Here both arguments are
generated by the same arm, so the compile check measures what the edited agent would actually write.

Per call: prompt + prefix truncated right after the last `new_string:<|"|>` (the served model's own text before it is
kept: file_path etc.); generate new_string until <|"|> (cap min(2048, 2*len(recorded new)+64) tokens); teacher-force
`<|"|>,old_string:<|"|>`; generate old_string until <|"|> (cap min(1024, 2*len(recorded old)+64)). An unclosed new_string
ends the draw (old_string empty -> the harness refuses it). Draw 0 greedy, draws 1.. sampled at T 0.6 / top_p 0.95 /
top_k 64; mx.random.seed(7919*index + draw) once per draw, the RNG then runs through both arguments. Prefill once per
call, KV cache copied per draw. The decoding loop is explicit (no generate_step), so exactly the tokens fed are cached.
Resumable: (key, draw) pairs already in --out are skipped.
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from replay_gen import MODEL, Q, apply_edit, usable  # noqa: E402

SEP = Q + ",old_string:" + Q


def split_prefix(r: dict) -> str:
    """The prefix up to and including `new_string:<|"|>`; asserts the recorded new_string follows it verbatim."""
    mark = "new_string:" + Q
    i = r["prefix"].rfind(mark)
    assert i >= 0, r["key"]
    head, tail = r["prefix"][: i + len(mark)], r["prefix"][i + len(mark):]
    assert tail.startswith(r.get("new_string") or ""), r["key"]
    assert tail.endswith(SEP), r["key"]
    return head


def main() -> None:
    import mlx.core as mx
    from mlx_lm.models.cache import make_prompt_cache
    from mlx_lm.sample_utils import make_sampler
    from mlx_lm.utils import load_model
    from tokenizers import Tokenizer

    ap = argparse.ArgumentParser()
    ap.add_argument("--calls", type=Path, required=True)
    ap.add_argument("--keys", type=Path, required=True)
    ap.add_argument("--draws", type=int, default=2)
    ap.add_argument("--edit", type=Path)
    ap.add_argument("--limit", type=int, help="first N keys only (smoke tests)")
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    idx = {r["key"]: r for r in usable(a.calls)}
    want = [l.strip() for l in a.keys.read_text().splitlines() if l.strip()]
    rows = [idx[k] for k in want if k in idx]
    assert len(rows) == len(want), f"{len(want) - len(rows)} keys not usable"
    if a.limit:
        rows = rows[: a.limit]
    tok = Tokenizer.from_file(str(MODEL / "tokenizer.json"))
    q_id = tok.token_to_id(Q)
    sep_ids = tok.encode(SEP, add_special_tokens=False).ids
    assert sep_ids[0] == q_id and sep_ids[-1] == q_id, sep_ids
    t0 = time.time()
    model, _ = load_model(MODEL, lazy=False, strict=True)
    changed = apply_edit(model, a.edit) if a.edit else []
    print(f"model loaded {time.time() - t0:.0f}s; edit modules {len(changed)}; calls {len(rows)}", flush=True)

    def decode(cache, first: list[int], sampler, max_new: int) -> tuple[list[int], int]:
        logits = model(mx.array(first)[None], cache=cache)[:, -1, :]
        out = []
        for _ in range(max_new):
            y = sampler(logits - mx.logsumexp(logits, axis=-1, keepdims=True))
            t = int(y.item())
            if t == q_id:
                return out, 1
            out.append(t)
            logits = model(mx.array([[t]]), cache=cache)[:, -1, :]
        return out, 0

    done = set()
    if a.out.exists():
        done = {(json.loads(l)["key"], json.loads(l)["draw"]) for l in a.out.open()}
    a.out.parent.mkdir(parents=True, exist_ok=True)
    with a.out.open("a") as out:
        for ci, r in enumerate(rows):
            if all((r["key"], d) in done for d in range(a.draws)):
                continue
            ids = tok.encode(r["prompt"] + split_prefix(r), add_special_tokens=False).ids
            ref_new = len(tok.encode(r.get("new_string") or "", add_special_tokens=False).ids)
            ref_old = len(tok.encode(r["old_string"], add_special_tokens=False).ids)
            cap_new, cap_old = min(2048, 2 * ref_new + 64), min(1024, 2 * ref_old + 64)
            t1 = time.time()
            cache = make_prompt_cache(model)
            for start in range(0, len(ids) - 1, 2048):
                model(mx.array(ids[start:min(start + 2048, len(ids) - 1)])[None], cache=cache)
                mx.eval([c.state for c in cache])
            t_prefill = time.time() - t1
            for d in range(a.draws):
                if (r["key"], d) in done:
                    continue
                sampler = make_sampler(temp=0.0) if d == 0 else make_sampler(temp=0.6, top_p=0.95, top_k=64)
                mx.random.seed(7919 * ci + d)
                c2 = copy.deepcopy(cache)
                t2 = time.time()
                new, closed_new = decode(c2, ids[-1:], sampler, cap_new)
                old, closed = decode(c2, sep_ids, sampler, cap_old) if closed_new else ([], 0)
                out.write(json.dumps({
                    "key": r["key"], "draw": d, "gen_new": tok.decode(new, skip_special_tokens=False),
                    "gen": tok.decode(old, skip_special_tokens=False), "closed_new": closed_new, "closed": closed,
                    "n_gen_new": len(new), "n_gen": len(old), "prompt_tokens": len(ids), "prefill_s": round(t_prefill, 1),
                    "gen_s": round(time.time() - t2, 1), "edit": str(a.edit) if a.edit else None}) + "\n")
                out.flush()
            print(f"[{ci + 1}/{len(rows)}] {r['key']} {r['error_kind']}/{r['strategy']} prompt {len(ids)} "
                  f"prefill {t_prefill:.1f}s", flush=True)
    print(f"done {time.time() - t0:.0f}s", flush=True)


if __name__ == "__main__":
    main()
